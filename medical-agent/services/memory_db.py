# TIER 2: SEMANTIC & EPISODIC MEMORY (pgvector)
# ==============================================================================

def generate_embedding(text: str) -> Optional[List[float]]:
    """
    Generate 768-dimensional embedding vector for text using Gemini.
    Uses `gemini-embedding-001` with `output_dimensionality=768`.
    """
    if not text or not str(text).strip():
        return None

    try:
        client = get_gemini_client()
        res = client.models.embed_content(
            model="gemini-embedding-001",
            contents=text.strip(),
            config=types.EmbedContentConfig(output_dimensionality=768),
        )
        if res and res.embeddings and len(res.embeddings) > 0:
            return res.embeddings[0].values
    except Exception as e:
        logger.error(f"Error generating embedding via Gemini: {e}")

    return None


def store_memory(
    phone_or_customer_id: str,
    content: str,
    memory_type: str = "general",
    metadata: Optional[Dict[str, Any]] = None,
    customer_id: Optional[str] = None,
) -> Optional[int]:
    """
    Store an episodic memory, order summary, customer preference, or note into `agent_memories`.
    Generates embedding and writes to PostgreSQL with pgvector.
    """
    if not content or not content.strip():
        return None

    norm_phone = normalize_phone(phone_or_customer_id)
    cust_id = customer_id or str(phone_or_customer_id)

    init_memory_db()

    embedding = generate_embedding(content)
    if not embedding:
        logger.warning("Failed to generate embedding for memory; storing without vector.")

    try:
        with get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    INSERT INTO agent_memories (phone, customer_id, memory_type, content, embedding, metadata)
                    VALUES (%s, %s, %s, %s, %s, %s)
                    RETURNING memory_id;
                    """,
                    (
                        norm_phone,
                        cust_id,
                        memory_type,
                        content.strip(),
                        embedding,
                        json.dumps(metadata or {}, ensure_ascii=False),
                    ),
                )
                row = cur.fetchone()
                mem_id = row[0] if row else None
                logger.info(f"Stored {memory_type} memory (id={mem_id}) for phone {norm_phone}: {content[:60]}...")
                return mem_id
    except Exception as e:
        logger.error(f"Error storing memory to DB: {e}")
        return None


def search_memories(
    phone_or_customer_id: str,
    query: str,
    limit: int = 3,
    threshold: float = 0.45,
    memory_type: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """
    Semantic search over customer memories using pgvector cosine distance `<=>`.
    Returns most relevant memories filtered for this customer's phone number.
    """
    if not query or not query.strip():
        return []

    norm_phone = normalize_phone(phone_or_customer_id)
    cust_id = str(phone_or_customer_id).strip()

    init_memory_db()
    query_vec = generate_embedding(query)
    if not query_vec:
        return []

    results = []
    try:
        with get_connection() as conn:
            with conn.cursor() as cur:
                type_filter = "AND memory_type = %s" if memory_type else ""
                params = [query_vec, norm_phone, cust_id]
                if memory_type:
                    params.append(memory_type)
                params.extend([query_vec, limit])

                cur.execute(
                    f"""
                    SELECT memory_id, memory_type, content, metadata, created_at,
                           1 - (embedding <=> %s::vector) AS similarity
                    FROM agent_memories
                    WHERE (phone = %s OR customer_id = %s)
                      AND embedding IS NOT NULL
                      {type_filter}
                    ORDER BY embedding <=> %s::vector ASC
                    LIMIT %s;
                    """,
                    params,
                )
                rows = cur.fetchall()
                for r in rows:
                    similarity = float(r[5]) if r[5] is not None else 0.0
                    if similarity >= threshold:
                        results.append({
                            "memory_id": r[0],
                            "memory_type": r[1],
                            "content": r[2],
                            "metadata": r[3] if isinstance(r[3], dict) else {},
                            "created_at": str(r[4]),
                            "similarity": round(similarity, 3),
                        })
    except Exception as e:
        logger.error(f"Error searching memories: {e}")

    return results


def get_customer_preferences(phone_or_customer_id: str, limit: int = 5) -> List[str]:
    """
    Retrieve stored customer preferences and special notes for a customer by phone number.
    Used for pre-prompting the agent with known customer preferences.
    """
    norm_phone = normalize_phone(phone_or_customer_id)
    if not norm_phone:
        return []

    init_memory_db()
    prefs = []
    try:
        with get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    SELECT content FROM agent_memories
                    WHERE phone = %s AND memory_type IN ('preference', 'note', 'medical_note')
                    ORDER BY memory_id DESC
                    LIMIT %s;
                    """,
                    (norm_phone, limit),
                )
                rows = cur.fetchall()
                for r in rows:
                    if r[0] and r[0].strip():
                        prefs.append(r[0].strip())
    except Exception as e:
        logger.warning(f"Error fetching customer preferences: {e}")

    return prefs
